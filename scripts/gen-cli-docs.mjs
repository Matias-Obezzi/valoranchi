import fs from "node:fs";
import path from "node:path";

const cliPath = path.resolve("src/cli.ts");
const content = fs.readFileSync(cliPath, "utf-8");
const match = content.match(/export const USAGE = `([\s\S]*?)`;/);

if (!match) {
  throw new Error("Could not find USAGE in src/cli.ts");
}

const lines = match[1].split("\n");
let currentSection = null;
const sections = [];

for (const rawLine of lines) {
  const line = rawLine.trimEnd();
  if (!line || line.startsWith("Usage:")) continue;
  if (/^[A-Za-z ()]+:$/.test(line)) {
    currentSection = {
      title: line.replace(":", ""),
      items: [],
    };
    sections.push(currentSection);
    continue;
  }
  if (!currentSection) continue;
  const trimmed = line.trim();
  const m = trimmed.match(/^([^A-Z]+?)\s+([A-Z].*)$/);
  if (m) {
    currentSection.items.push({
      name: m[1].trim(),
      desc: m[2].trim(),
    });
  }
}

const outDir = path.resolve("docs/guide");
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

let md = "<!-- This file is auto-generated by scripts/gen-cli-docs.mjs from src/cli.ts USAGE -->\n\n";

for (const section of sections) {
  const isOptions = section.title === "Options";
  md += `### ${section.title}\n\n`;
  md += `| ${isOptions ? "Option" : "Command"} | Description |\n`;
  md += "| :--- | :--- |\n";
  for (const item of section.items) {
    const escapedName = item.name.replace(/\|/g, "\\|");
    const escapedDesc = item.desc
      .replace(/\|/g, "\\|")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
    md += `| \`${escapedName}\` | ${escapedDesc} |\n`;
  }
  md += "\n";
}

const outFile = path.join(outDir, "cli-commands.md");
fs.writeFileSync(outFile, md, "utf-8");
console.log(`Generated ${outFile}`);
